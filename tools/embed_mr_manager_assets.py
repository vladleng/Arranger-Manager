"""Offline, deterministic embedding of pinned upstream MR UDS icons and tokens."""
import hashlib
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / 'assets/ui/mr-uds'
OUTPUT = ROOT / 'src/MRManagerAssets.h'

def generate():
    provenance = json.loads((KIT / 'UPSTREAM.json').read_text(encoding='utf-8'))
    for path, expected in provenance['sha256'].items():
        data = (KIT / path).read_bytes()
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError('Upstream asset changed: ' + path)
    catalog = json.loads((KIT / 'catalogs/manager-v1.json').read_text(encoding='utf-8'))
    tokens = json.loads((KIT / 'tokens/manager.json').read_text(encoding='utf-8'))
    output = ['// Generated by tools/embed_mr_manager_assets.py; do not edit.',
              '// MR-Studio f0c3a67d2c67d1d9ff863bccc01eb11fb9e6cdb5; original MR artwork.',
              '#pragma once', '#include <cstdint>', 'namespace mr::tokens {']
    for name, value in tokens['colors'].items():
        assert len(value) == 7 and value.startswith('#')
        output.append(f'inline constexpr std::uint32_t {name} = 0xff{value[1:]}u;')
    output += ['}', 'namespace mr::assets {', 'struct SvgSource { const char* id; const char* xml; };',
               'inline constexpr SvgSource icons[] = {']
    seen = set()
    for asset in catalog['assets']:
        assert asset['id'] not in seen
        seen.add(asset['id'])
        svg = (KIT / asset['file']).read_text(encoding='utf-8')
        xml = ET.fromstring(svg)
        assert xml.tag == '{http://www.w3.org/2000/svg}svg' and xml.get('viewBox')
        for element in xml.iter():
            assert element.tag.split('}')[-1] in {'svg','title','desc','g','path','rect','circle','ellipse','line','polyline','polygon','text','tspan'}
            for key,value in element.attrib.items():
                assert not key.lower().endswith('href') and not key.lower().startswith('on')
                assert 'url(' not in value.lower()
        if asset['usage'] != 'icon':
            continue  # Never embed illustrative names/values as runtime UI.
        assert ')MR_SVG"' not in svg
        output.append('    {"' + asset['id'] + '", R"MR_SVG(' + svg + ')MR_SVG"},')
    output += ['};', '}', '']
    return '\n'.join(output)

content = generate()
if '--check' in sys.argv:
    if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != content:
        raise SystemExit('MRManagerAssets.h is stale; regenerate offline')
    print('Pinned SVG/catalog/tokens and generated header agree')
else:
    OUTPUT.write_text(content, encoding='utf-8', newline='')
